// Writes .env.local from the running local Supabase stack (`npm run db:env`).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let status;
try {
  status = JSON.parse(
    execFileSync("supabase", ["status", "-o", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }),
  );
} catch {
  console.error("Local Supabase is not running. Start it with `npm run db:start` first.");
  process.exit(1);
}

const url = status.API_URL;
const publishableKey = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
const secretKey = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;

if (!url || !publishableKey) {
  console.error("Could not read API_URL / PUBLISHABLE_KEY from `supabase status`.");
  process.exit(1);
}

const lines = [
  "# Generated by `npm run db:env` from the local Supabase stack. Do not commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${url}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
  "",
  "# Server-only. Bypasses RLS — never expose to the browser.",
  `SUPABASE_SECRET_KEY=${secretKey ?? ""}`,
  "",
];

writeFileSync(".env.local", lines.join("\n"));
console.log(`Wrote .env.local (${url})`);
